function toCountryCode(value) {
  const raw = String(value || "").trim();
  if (/^[a-z]{2}$/i.test(raw)) return raw.toUpperCase();
  const key = raw.toLowerCase().replace(/[.'’]/g, "").replace(/\s+/g, " ").trim();
  return names[key] || "";
}

